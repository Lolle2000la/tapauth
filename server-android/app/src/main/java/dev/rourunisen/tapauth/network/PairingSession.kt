/** Which transport won the pairing race (plan §6.4). */
enum class PairingTransport {
    UDP,
    BLE,
}

/** Everything the pairing UI has to render, emitted in order by [PairingSession.start]. */
sealed class PairingUpdate {
    data object Connecting : PairingUpdate()

    data class AwaitingSas(val sas: String, val transport: PairingTransport) : PairingUpdate()

    data class Confirming(val transport: PairingTransport) : PairingUpdate()

    data class Complete(val device: PairedDevice) : PairingUpdate()

    /** User-facing reason; safe to render as-is. */
    data class Failed(val message: String) : PairingUpdate()

    data object Cancelled : PairingUpdate()
}

/**
 * Orchestrates protocol v2 pairing (`docs/design-documents/protocol/initial-key-exchange.md`) as
 * the pairing **Server**: Android sends `PairingInit` and verifies the Client's `PairingResponse`,
 * so the QR code (generated by the Linux Client) supplies the session id and the Client's ephemeral
 * X25519 public key, and the phone supplies its long-term Ed25519 identity.
 *
 * ### The whole handshake state lives in Rust
 *
 * [TapAuthCrypto.pairingServerSessionCreate] returns an opaque handle that owns the phone's
 * ephemeral `X_S`, `Ed_S`, the directional keys `K_c2s`/`K_s2c` and the transcript hash `H`. This
 * class never sees any of them: it holds the handle, moves whole serialized `PairingPacket` blobs,
 * and reads back only what it persists (the SAS, the Client's `Ed_C` and the three negotiated
 * algorithm ids). Abort MAC direction, AAD construction and key derivation are therefore not
 * Kotlin's to get wrong.
 *
 * One shared init state — one handle, one serialized `PairingInit` — feeds both transport
 * candidates, because the transcript hash binds the init bytes: two different `PairingInit`
 * payloads would derive two different SAS values. The UDP and BLE candidates race; the first one
 * that delivers a `PairingResponse` accepted by [TapAuthCrypto.pairingVerifyResponse] locks the
 * transport and the loser is cancelled. A response that fails verification is logged and ignored —
 * one injected bad packet must not end the session — and only an authenticated `PairingAbort` (or
 * the deadline) ends it early.
 *
 * ### The QR pin is mandatory
 *
 * [qrPublicKey] is the QR code's `pk` and is always compared, in constant time, inside Rust against
 * `PairingResponse.client_x25519_public_key`. There is no "no pin available" path:
 * [PairingUrl.parse] requires a 64-hex `pk`, so every reachable session is pinned.
 *
 * ### Threading
 *
 * Callers hand in their own [CoroutineScope]; this class never creates one. All socket/GATT work
 * runs on [Dispatchers.IO] and every [PairingUpdate] is delivered on the main thread, so a Compose
 * screen can consume them directly. [start], [approveSas], [rejectSas] and [close] may be called
 * from the main thread at any time and in any order; they only publish intent to the running
 * coroutine.
 */
class PairingSession(
    private val context: Context,
    private val pairingUrl: PairingUrl,
    private val clientDeviceName: String = Build.MODEL,
    private val qrPublicKey: ByteArray = pairingUrl.publicKeyBytes(),
) {

    companion object {
        private const val TAG = "PairingSession"

        private const val SESSION_ID_BYTES = 16

        /** `PairingInit.server_device_name` is capped at 64 UTF-8 bytes by the proto. */
        private const val MAX_SERVER_NAME_BYTES = 64

        /**
         * Cap for the peer-chosen `client_hostname` before it is persisted as
         * [PairedDevice.displayName] and rendered in the biometric prompt.
         */
        private const val MAX_CLIENT_NAME_BYTES = 64

        private const val DEFAULT_SERVER_NAME = "Android Device"

        /** Shown when neither the provision payload nor an existing record names the desktop. */
        private const val DEFAULT_CLIENT_NAME = "Unknown desktop"

        /** Protocol version persisted for a v2 pairing (plan §1). */
        private const val PROTOCOL_VERSION = 2

        /** `PairingInit` retransmission interval while no `PairingResponse` has arrived. */
        private const val INIT_RETRANSMIT_INTERVAL_MS = 500L

        /** How long `PairingInit` is retransmitted before only listening (docs: up to 15 s). */
        private const val INIT_RETRANSMIT_WINDOW_MS = 15_000L

        /** `PairingKeepalive` interval while waiting for `PairingConfirmClient` (docs: 1000 ms). */
        private const val KEEPALIVE_INTERVAL_MS = 1000L

        /** Head start for the LAN candidate before BLE starts scanning (docs: 250 ms). */
        private const val BLE_HEAD_START_MS = 250L

        /** Receive slice, so user decisions are acted on promptly while a transport blocks. */
        private const val RECEIVE_SLICE_MS = 200L

        /** How long the two candidates race for a valid `PairingResponse`. */
        private const val RESPONSE_DEADLINE_MS = 30_000L

        /** How long the phone waits for `PairingConfirmClient` after the user approved the SAS. */
        private const val CONFIRM_TIMEOUT_MS = 120_000L

        /**
         * How long the SAS screen may stay up unanswered before the session expires.
         *
         * This is the pairing-session lifetime rather than a UI deadline: the user has already
         * scanned the QR code, so the ephemeral X25519 key, the GATT link and the UDP socket stay
         * bound to a live session until they answer or this bound fires.
         */
        private const val SAS_APPROVAL_TIMEOUT_MS = 180_000L

        /** `PairingConfirmServer` retransmissions over UDP, relative to the first send. */
        private const val CONFIRM_RETRANSMIT_1_MS = 100L
        private const val CONFIRM_RETRANSMIT_2_MS = 150L

        /** Shown when the SAS prompt goes unanswered past [SAS_APPROVAL_TIMEOUT_MS]. */
        private const val SAS_EXPIRED_MESSAGE = "The pairing session expired"

        /**
         * Shown for a verified abort from the desktop.
         *
         * `pairingVerifyAbort` returns only a `Boolean`, so the remote `PairingAbortReason` is not
         * available here; a reason-specific string is only reachable for a reason this phone chose
         * itself.
         */
        private const val REMOTE_ABORT_MESSAGE = "The desktop aborted the pairing"
    }

    private val deviceRepository = DeviceRepository(context)
    private val keypairRepository = KeypairRepository(context)

    private val sessionId = pairingUrl.sessionIdBytes()

    // Ephemeral session state. The keys never leave Rust behind the handle; the handshake buffers
    // below are cleared on completion/abort/close.
    @Volatile private var initPacket: ByteArray? = null
    @Volatile private var acceptedResponsePacket: ByteArray? = null

    /**
     * The Rust pairing session handle, or `0` before [prepareSession] / after
     * [zeroizeEphemeralState].
     *
     * `0` is never a valid handle (Rust starts its allocator at 1), so it is the natural "nothing
     * to free" value, and the swap to `0` is what makes freeing idempotent.
     */
    private val handleLock = Any()
    @Volatile private var pairingHandle: Long = 0L

    private val links = mutableListOf<PairingLink>()

    @Volatile private var job: Job? = null

    @Volatile private var onUpdate: ((PairingUpdate) -> Unit)? = null

    /**
     * A frame that arrived while the SAS screen was up and was not an abort. It cannot be consumed
     * yet (the provision payload is only expected after approval), and over BLE there is no 500 ms
     * retransmission to fall back on, so it is kept for [awaitProvision].
     */
    @Volatile private var stashedPacket: ByteArray? = null

    private val closed = AtomicBoolean(false)

    /** Completed by [approveSas] / [rejectSas]; drives the transition out of the SAS screen. */
    private val userDecision = CompletableDeferred<UserDecision>()

    /**
     * Main-thread dispatcher for [onUpdate], or null on a plain JVM (unit tests) where no Main
     * dispatcher module is installed.
     *
     * `Dispatchers.Main.immediate` does **not** throw without a Main provider — it hands back a
     * `MissingMainCoroutineDispatcher` whose *dispatch* throws — so the only honest probe is a
     * trivial dispatch. [resolveMainDispatcher] performs it once and memoizes the answer.
     */
    @Volatile private var mainDispatcherResolved = false
    @Volatile private var mainDispatcher: CoroutineDispatcher? = null

    /**
     * Run the pairing session, reporting progress through [onUpdate].
     *
     * Call once; a second call is ignored (logged) so a recomposition cannot start a second
     * handshake on top of the first.
     */
    fun start(scope: CoroutineScope, onUpdate: (PairingUpdate) -> Unit) {
        if (job != null) {
            Log.w(TAG, "start() ignored: this session is already running")
            return
        }
        this.onUpdate = onUpdate
        job = scope.launch(Dispatchers.IO) { runSession() }
    }

    /** The user confirmed the SAS matches. Sends no packet until `PairingConfirmClient` arrives. */
    fun approveSas() {
        userDecision.complete(UserDecision.Approve)
    }

    /** The user says the SAS differs: send an authenticated `PairingAbort(USER_REJECTED_SAS)`. */
    fun rejectSas() {
        userDecision.complete(UserDecision.Reject)
    }

    /**
     * Cancel everything: running coroutines, sockets, GATT, and the Rust pairing session.
     *
     * Idempotent, so it is safe from `DisposableEffect`, back navigation, or a second call after
     * the session already finished.
     */
    fun close() {
        if (!closed.compareAndSet(false, true)) return
        job?.cancel()
        // Close the transports directly as well: a coroutine parked in a blocking socket read only
        // notices cancellation after its current slice.
        closeLinks()
        zeroizeEphemeralState()
    }

    private suspend fun runSession() {
        try {
            if (closed.get()) return
            emit(PairingUpdate.Connecting)
            val init = prepareSession()

            val locked = raceForResponse(init) ?: return
            val response = locked.response

            emit(PairingUpdate.AwaitingSas(response.sas, locked.transport))

            when (val approval = awaitApproval(locked)) {
                is Approval.Approved -> Unit
                is Approval.Rejected -> {
                    sendAbort(locked, TapAuthCrypto.PAIRING_ABORT_USER_REJECTED_SAS)
                    emit(PairingUpdate.Cancelled)
                    return
                }
                is Approval.Aborted -> {
                    emitFailure(REMOTE_ABORT_MESSAGE)
                    return
                }
                is Approval.Expired -> {
                    emitFailure(SAS_EXPIRED_MESSAGE)
                    return
                }
                is Approval.Cancelled -> {
                    emit(PairingUpdate.Cancelled)
                    return
                }
            }

            emit(PairingUpdate.Confirming(locked.transport))

            when (val outcome = awaitProvision(locked)) {
                is ProvisionOutcome.Completed -> emit(PairingUpdate.Complete(outcome.device))
                is ProvisionOutcome.Aborted -> emitFailure(REMOTE_ABORT_MESSAGE)
                is ProvisionOutcome.TimedOut ->
                    emitFailure("The desktop did not finish pairing in time")
                is ProvisionOutcome.Cancelled -> emit(PairingUpdate.Cancelled)
            }
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "Pairing failed", e)
            emitFailure(e.message ?: "Pairing failed")
        } finally {
            closeLinks()
            zeroizeEphemeralState()
        }
    }

    /**
     * Create the phone's pairing session in Rust and build the one shared `PairingInit`.
     *
     * Rust owns the ephemeral `X_S` and `Ed_S` from here on; the baseline algorithms are listed
     * first by the Rust side (plan §1.1), so Kotlin does not choose the advertised order.
     */
    private suspend fun prepareSession(): ByteArray {
        require(sessionId.size == SESSION_ID_BYTES) {
            "Pairing session id must be $SESSION_ID_BYTES bytes, got ${sessionId.size}"
        }

        val identity = withContext(Dispatchers.IO) { keypairRepository.getKeypair() }
        val serverName =
            ContextSanitizer.sanitize(clientDeviceName, MAX_SERVER_NAME_BYTES).ifBlank {
                DEFAULT_SERVER_NAME
            }

        // `0` means the create failed (it throws as well); a zero handle must never be used.
        val handle =
            TapAuthCrypto.pairingServerSessionCreate(sessionId, identity.privateKey, serverName)
        if (handle <= 0L) throw IllegalStateException("Could not create a pairing session")
        synchronized(handleLock) { pairingHandle = handle }

        val init = TapAuthCrypto.pairingCreateInit(handle)
        initPacket = init
        Log.d(TAG, "PairingInit prepared for session ${sessionId.toHex().take(8)}…")
        return init
    }

    /**
     * Race the two transports for a verified `PairingResponse`.
     *
     * @return the locked transport plus what the phone persists from the response, or null after
     *   emitting `Failed`
     */
    private suspend fun raceForResponse(init: ByteArray): Locked? {
        val udpAvailable =
            pairingUrl.port != null && (pairingUrl.ipv4 != null || pairingUrl.ipv6 != null)
        val outcome = CompletableDeferred<Locked?>()
        val candidates = if (udpAvailable) 2 else 1
        val remaining = AtomicInteger(candidates)

        return coroutineScope {
            fun finished() {
                if (remaining.decrementAndGet() == 0) outcome.complete(null)
            }

            val udpJob =
                if (udpAvailable) {
                    launch {
                        try {
                            withTimeoutOrNull(RESPONSE_DEADLINE_MS) { udpCandidate(init, outcome) }
                        } finally {
                            finished()
                        }
                    }
                } else {
                    null
                }
            val bleJob = launch {
                try {
                    // Give the LAN candidate a head start; with no UDP endpoint BLE is the only
                    // one.
                    if (udpAvailable) delay(BLE_HEAD_START_MS)
                    withTimeoutOrNull(RESPONSE_DEADLINE_MS) { bleCandidate(init, outcome) }
                } finally {
                    finished()
                }
            }

            val locked = outcome.await()
            // The loser has to be cancelled explicitly: coroutineScope waits for every child, and
            // the
            // loser would otherwise keep retransmitting until its own deadline.
            udpJob?.cancel()
            bleJob.cancel()

            if (locked == null) {
                emitFailure(
                    if (udpAvailable) {
                        "No response from the desktop. Check the network and that Bluetooth is on."
                    } else {
                        "This QR code has no network endpoint and Bluetooth pairing is unavailable."
                    },
                )
            }
            locked
        }
    }

    private suspend fun udpCandidate(init: ByteArray, outcome: CompletableDeferred<Locked?>) {
        val link = UdpPairingLink(PairingClient(pairingUrl))
        registerLink(link)
        var won = false
        try {
            try {
                link.open()
            } catch (e: IOException) {
                Log.w(TAG, "UDP pairing candidate unavailable: ${e.message}")
                return
            }
            var nextSend = 0L
            val retransmitUntil = System.currentTimeMillis() + INIT_RETRANSMIT_WINDOW_MS
            while (true) {
                val now = System.currentTimeMillis()
                if (now >= nextSend && now < retransmitUntil) {
                    link.send(init)
                    nextSend = now + INIT_RETRANSMIT_INTERVAL_MS
                }
                val packet = receivePacket(link) ?: continue
                val response = acceptResponse(packet) ?: continue
                won = outcome.complete(Locked(PairingTransport.UDP, link, response))
                if (!won) Log.d(TAG, "UDP response arrived after another transport won")
                return
            }
        } finally {
            if (!won) link.close()
        }
    }

    private suspend fun bleCandidate(init: ByteArray, outcome: CompletableDeferred<Locked?>) {
        val client = BlePairingClient(context)
        val link = BlePairingLink(client)
        registerLink(link)
        var won = false
        try {
            val advertisementId = TapAuthCrypto.deriveBlePairingAdvId(sessionId, qrPublicKey)
            if (!client.connect(advertisementId, RESPONSE_DEADLINE_MS)) {
                Log.w(TAG, "BLE pairing candidate unavailable")
                return
            }
            // One acknowledged write is enough over GATT: the Client already holds the socket open.
            if (!link.send(init)) {
                Log.w(TAG, "BLE PairingInit write failed")
                return
            }
            while (true) {
                val packet = receivePacket(link) ?: continue
                val response = acceptResponse(packet) ?: continue
                won = outcome.complete(Locked(PairingTransport.BLE, link, response))
                if (!won) Log.d(TAG, "BLE response arrived after UDP won")
                return
            }
        } finally {
            if (!won) link.close()
        }
    }

    /**
     * The next frame on [link] that belongs to this pairing session.
     *
     * The BLE characteristic and the pairing UDP port are shared with any other pairing in flight,
     * so a frame carrying a different `session_id` is dropped before any crypto is spent on it.
     *
     * @return the frame, or null when the receive slice expired
     */
    private suspend fun receivePacket(link: PairingLink): ByteArray? {
        while (true) {
            val packet = link.receive(RECEIVE_SLICE_MS) ?: return null
            if (belongsToSession(packet)) return packet
            Log.d(TAG, "Dropping a pairing frame that belongs to another session")
        }
    }

    /** Whether [packet] is a v2 `PairingPacket` for [sessionId]. */
    private fun belongsToSession(packet: ByteArray): Boolean =
        try {
            TapAuthCrypto.pairingPacketSessionId(packet).contentEquals(sessionId)
        } catch (e: Exception) {
            Log.d(TAG, "Dropping an undecodable pairing frame: ${e.message}")
            false
        }

    /**
     * Verify a candidate `PairingResponse`.
     *
     * The QR pin, the Client's signature over the transcript hash and the algorithm intersection
     * are all checked inside Rust, against the handle — Kotlin cannot accidentally skip any of
     * them.
     *
     * @return the response's persistable fields, or null when the packet is not an acceptable
     *   response (wrong packet type, QR `pk` mismatch, bad signature, unsupported algorithm). Never
     *   throws: an injected bad packet must not end the session.
     */
    private fun acceptResponse(packet: ByteArray): ParsedPairingResponse? {
        val handle = synchronized(handleLock) { pairingHandle }
        if (handle == 0L) return null
        val response =
            try {
                TapAuthCrypto.pairingVerifyResponse(handle, packet, qrPublicKey)
            } catch (e: GeneralSecurityException) {
                Log.w(TAG, "PairingResponse rejected: ${e.message}")
                return null
            } catch (e: Exception) {
                // Not a PairingResponse (keepalive/abort/duplicate), or a malformed frame.
                Log.d(TAG, "Ignoring packet that is not a valid PairingResponse: ${e.message}")
                return null
            }
        acceptedResponsePacket = packet
        Log.i(TAG, "PairingResponse accepted, SAS ${response.sas}")
        return response
    }

    /**
     * Wait for the user's SAS decision, still watching the locked transport so an authenticated
     * `PairingAbort` from the desktop (it aborts when its own user rejects) is honoured.
     *
     * Bounded by [SAS_APPROVAL_TIMEOUT_MS]: a user who walks away after scanning must not leave the
     * GATT link, the UDP socket and this coroutine alive forever. Expiry aborts the session with
     * `SESSION_EXPIRED` so the desktop learns why, exactly like the other phases.
     */
    private suspend fun awaitApproval(locked: Locked): Approval {
        val deadline = System.currentTimeMillis() + SAS_APPROVAL_TIMEOUT_MS
        while (System.currentTimeMillis() < deadline) {
            if (closed.get()) return Approval.Cancelled
            if (userDecision.isCompleted) {
                return when (userDecision.await()) {
                    UserDecision.Approve -> Approval.Approved
                    UserDecision.Reject -> Approval.Rejected
                }
            }
            val packet = receivePacket(locked.link) ?: continue
            if (isVerifiedAbort(packet)) {
                Log.i(TAG, "Desktop aborted pairing before approval")
                return Approval.Aborted
            }
            if (stashedPacket == null) stashedPacket = packet
        }
        Log.i(TAG, "SAS approval timed out after ${SAS_APPROVAL_TIMEOUT_MS}ms")
        sendAbort(locked, TapAuthCrypto.PAIRING_ABORT_SESSION_EXPIRED)
        return Approval.Expired
    }

    /**
     * Wait for `PairingConfirmClient`, keeping the UDP NAT mapping alive with `PairingKeepalive`.
     *
     * On `PairingConfirmClient`: decrypt the provision payload inside Rust, persist the
     * `PairedDevice`, send `PairingConfirmServer` back and report [ProvisionOutcome] completion.
     */
    private suspend fun awaitProvision(locked: Locked): ProvisionOutcome {
        val handle = synchronized(handleLock) { pairingHandle }
        val keepalive =
            if (locked.transport == PairingTransport.UDP && handle != 0L) {
                TapAuthCrypto.pairingCreateKeepalive(handle)
            } else {
                null
            }
        var nextKeepalive = 0L
        val deadline = System.currentTimeMillis() + CONFIRM_TIMEOUT_MS

        while (System.currentTimeMillis() < deadline) {
            if (closed.get()) return ProvisionOutcome.Cancelled
            if (keepalive != null && System.currentTimeMillis() >= nextKeepalive) {
                locked.link.send(keepalive)
                nextKeepalive = System.currentTimeMillis() + KEEPALIVE_INTERVAL_MS
            }
            val stashed = stashedPacket
            stashedPacket = null
            val packet = stashed ?: receivePacket(locked.link) ?: continue

            val provision = processConfirmClient(packet)
            if (provision != null) return finishPairing(locked, provision)

            if (isVerifiedAbort(packet)) {
                Log.i(TAG, "Desktop aborted pairing while awaiting the provision payload")
                return ProvisionOutcome.Aborted
            }
        }
        return ProvisionOutcome.TimedOut
    }

    /**
     * Decrypt `PairingConfirmClient` in Rust; null when [packet] is something else entirely.
     *
     * The AEAD AAD is `"tapauth-pair-v2-provision" || H` built inside the handle, so Kotlin cannot
     * get it wrong and cannot be tricked into reusing the wrong transcript.
     */
    private fun processConfirmClient(packet: ByteArray): ParsedPairingProvision? {
        val handle = synchronized(handleLock) { pairingHandle }
        if (handle == 0L) return null
        return try {
            TapAuthCrypto.pairingProcessConfirmClient(handle, packet)
        } catch (e: GeneralSecurityException) {
            Log.d(TAG, "Not a decryptable PairingConfirmClient: ${e.message}")
            null
        } catch (e: Exception) {
            Log.d(TAG, "Ignoring packet while awaiting PairingConfirmClient: ${e.message}")
            null
        }
    }

    /** Persist the device, confirm to the desktop, and report completion. */
    private suspend fun finishPairing(
        locked: Locked,
        provision: ParsedPairingProvision,
    ): ProvisionOutcome {
        val handle = synchronized(handleLock) { pairingHandle }
        check(handle != 0L) { "Pairing session was released before the completion proof" }
        // Build the confirmation before persisting: a failure here must not leave a device record
        // for a pairing the desktop never accepted. Rust signs `"tapauth-pair-server-sig-v2" || H
        // ||
        // csk` with `Ed_S` and encrypts it under `K_s2c`.
        val confirmServer = TapAuthCrypto.pairingCreateConfirmServer(handle, provision.csk)

        val device = persistDevice(locked.response, provision)

        when (locked.transport) {
            // 3× at 0 ms / 100 ms / 250 ms so a lost datagram does not leave the desktop pairing.
            PairingTransport.UDP -> {
                locked.link.send(confirmServer)
                delay(CONFIRM_RETRANSMIT_1_MS)
                locked.link.send(confirmServer)
                delay(CONFIRM_RETRANSMIT_2_MS)
                locked.link.send(confirmServer)
            }
            PairingTransport.BLE -> {
                if (!locked.link.send(confirmServer)) {
                    Log.w(TAG, "BLE PairingConfirmServer write failed; device record is kept")
                }
            }
        }

        zeroizeEphemeralState()
        return ProvisionOutcome.Completed(device)
    }

    /**
     * Save the paired device, merging with any existing record for the same Client identity.
     *
     * `deviceId` is the hex of the Client's Ed25519 public key: stable across re-pairings, so a
     * second pairing by another user of the same desktop appends to `allowedUsers` instead of
     * creating a second record that could never be matched by signature.
     *
     * `displayName` comes from the peer-supplied `client_hostname`, so it is sanitized here before
     * it is persisted and later rendered in the biometric approval prompt.
     */
    private suspend fun persistDevice(
        response: ParsedPairingResponse,
        provision: ParsedPairingProvision,
    ): PairedDevice {
        val deviceId = response.clientEd25519PublicKey.toHex()
        val existing = runCatching { deviceRepository.getPairedDevice(deviceId) }.getOrNull()

        val allowedUsers = buildList {
            addAll(existing?.allowedUsers.orEmpty())
            val username = provision.username
            if (username.isNotBlank() && username !in this) add(username)
        }
        val displayName =
            ContextSanitizer.sanitize(provision.clientHostname, MAX_CLIENT_NAME_BYTES).ifBlank {
                existing?.displayName?.ifBlank { null } ?: DEFAULT_CLIENT_NAME
            }

        val device =
            PairedDevice(
                deviceId = deviceId,
                publicKey = response.clientEd25519PublicKey,
                csk = provision.csk,
                displayName = displayName,
                pairedAt = System.currentTimeMillis(),
                allowedUsers = allowedUsers,
                symmetricAlgorithm = response.symmetricAlgorithm,
                hashAlgorithm = response.hashAlgorithm,
                signatureAlgorithm = response.signatureAlgorithm,
                protocolVersion = PROTOCOL_VERSION,
            )
        deviceRepository.savePairedDevice(device)
        Log.i(TAG, "Paired '$displayName' for user(s) $allowedUsers")
        return device
    }

    /**
     * Send an authenticated `PairingAbort` on the locked transport.
     *
     * The MAC direction is Rust's: `ClientPairingSession::create_abort` tags with `K_s2c` (the
     * phone→desktop direction of `cryptography-specification.md` §2.2) and verifies incoming aborts
     * with `K_c2s`, so passing a key here would be both redundant and a way to break it.
     */
    private suspend fun sendAbort(locked: Locked, reason: Int) {
        val handle = synchronized(handleLock) { pairingHandle }
        if (handle == 0L) {
            Log.w(TAG, "No pairing session to abort with")
            return
        }
        val abort =
            try {
                TapAuthCrypto.pairingCreateAbort(handle, reason)
            } catch (e: Exception) {
                Log.e(TAG, "Could not build PairingAbort", e)
                return
            }
        when (locked.transport) {
            PairingTransport.UDP -> {
                locked.link.send(abort)
                delay(CONFIRM_RETRANSMIT_1_MS)
                locked.link.send(abort)
            }
            PairingTransport.BLE -> locked.link.send(abort)
        }
    }

    /**
     * Whether [packet] is an authenticated `PairingAbort` from the desktop.
     *
     * `false` from Rust means the abort carried no tag because no key existed yet — unauthenticated
     * by construction, so it is ignored rather than honoured. A thrown tag failure or a foreign
     * packet means "not an abort / forged" and is ignored the same way; neither may end the
     * session.
     */
    private fun isVerifiedAbort(packet: ByteArray): Boolean {
        val handle = synchronized(handleLock) { pairingHandle }
        if (handle == 0L) return false
        return try {
            TapAuthCrypto.pairingVerifyAbort(handle, packet)
        } catch (e: GeneralSecurityException) {
            false
        } catch (e: Exception) {
            Log.d(TAG, "Ignoring packet while checking for PairingAbort: ${e.message}")
            false
        }
    }

    private fun registerLink(link: PairingLink) {
        synchronized(links) { links.add(link) }
    }

    private fun closeLinks() {
        val snapshot = synchronized(links) { links.toList() }
        for (link in snapshot) {
            try {
                link.close()
            } catch (e: Exception) {
                Log.d(TAG, "Closing transport failed: ${e.message}")
            }
        }
    }

    /**
     * Release the pairing session and clear the handshake buffers.
     *
     * The Rust handle owns `x_S`, `K_c2s`, `K_s2c` and `H` (`cryptography-specification.md` §4),
     * and dropping it zeroizes them, so "release the handle" is the whole of zeroization here.
     * `Ed_S` is the phone's long-term identity key and lives in Rust's identity copy, untouched.
     *
     * Idempotent: the handle is swapped to `0` under the lock, and an already-freed handle (Rust
     * throws `IllegalArgumentException`) is tolerated because [close] and the session epilogue can
     * both reach this.
     */
    private fun zeroizeEphemeralState() {
        val handle = synchronized(handleLock) { pairingHandle.also { pairingHandle = 0L } }
        if (handle != 0L) {
            try {
                TapAuthCrypto.pairingServerSessionFree(handle)
            } catch (e: IllegalArgumentException) {
                Log.d(TAG, "Pairing session handle $handle was already released")
            } catch (e: Exception) {
                Log.w(TAG, "Failed to release pairing session handle $handle: ${e.message}")
            }
        }
        initPacket?.fill(0)
        initPacket = null
        acceptedResponsePacket?.fill(0)
        acceptedResponsePacket = null
    }

    private suspend fun emit(update: PairingUpdate) {
        val callback = onUpdate ?: return
        val dispatcher = resolveMainDispatcher()
        if (dispatcher == null) {
            callback(update)
        } else {
            withContext(dispatcher) { callback(update) }
        }
    }

    /**
     * The Main dispatcher, or null when this JVM has none — probed by dispatching, memoized so the
     * probe costs one dispatch per session.
     *
     * On Android Main always exists, so updates are always delivered on the main thread there. A
     * plain JVM (unit tests) has no Main provider, and delivering inline keeps the update that
     * reports the failure from being the one that is lost.
     */
    private suspend fun resolveMainDispatcher(): CoroutineDispatcher? {
        if (mainDispatcherResolved) return mainDispatcher
        val candidate = Dispatchers.Main.immediate
        val usable =
            try {
                withContext(candidate) {}
                true
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.d(
                    TAG,
                    "No Main dispatcher (${e.javaClass.simpleName}); delivering updates inline",
                )
                false
            }
        mainDispatcher = if (usable) candidate else null
        mainDispatcherResolved = true
        return mainDispatcher
    }

    private suspend fun emitFailure(message: String) {
        Log.w(TAG, "Pairing failed: $message")
        emit(PairingUpdate.Failed(message))
    }

    /** Locked transport plus what the verified `PairingResponse` said. */
    private class Locked(
        val transport: PairingTransport,
        val link: PairingLink,
        val response: ParsedPairingResponse,
    )

    private sealed class UserDecision {
        data object Approve : UserDecision()

        data object Reject : UserDecision()
    }

    private sealed class Approval {
        data object Approved : Approval()

        data object Rejected : Approval()

        /** A verified `PairingAbort` from the desktop. */
        data object Aborted : Approval()

        data object Cancelled : Approval()

        /** Nobody answered within [SAS_APPROVAL_TIMEOUT_MS]; the abort has already been sent. */
        data object Expired : Approval()
    }

    private sealed class ProvisionOutcome {
        data class Completed(val device: PairedDevice) : ProvisionOutcome()

        /** A verified `PairingAbort` from the desktop. */
        data object Aborted : ProvisionOutcome()

        data object TimedOut : ProvisionOutcome()

        data object Cancelled : ProvisionOutcome()
    }
}

/** Uniform view over either transport, so the session logic is written once. */
private interface PairingLink {
    suspend fun send(packet: ByteArray): Boolean

    suspend fun receive(timeoutMs: Long): ByteArray?

    fun close()
}

private class UdpPairingLink(private val client: PairingClient) : PairingLink {
    suspend fun open() = withContext(Dispatchers.IO) { client.open() }

    override suspend fun send(packet: ByteArray): Boolean =
        withContext(Dispatchers.IO) {
            client.send(packet)
            true
        }

    override suspend fun receive(timeoutMs: Long): ByteArray? = client.receive(timeoutMs)

    override fun close() = client.close()
}

private class BlePairingLink(private val client: BlePairingClient) : PairingLink {
    override suspend fun send(packet: ByteArray): Boolean = client.send(packet)

    override suspend fun receive(timeoutMs: Long): ByteArray? = client.awaitPacket(timeoutMs)

    override fun close() = client.close()
}

private fun ByteArray.toHex(): String = joinToString("") { "%02x".format(it) }
